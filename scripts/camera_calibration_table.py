#!/usr/bin/env python3
"""FedRGBD -- the revision cameras' calibration, from the study capture records.

Prereg Amendment 3 (``docs/CAMERA_EXPERIMENT_PREREG.md`` section 12) makes every capture
record carry the cameras' calibration: intrinsics with distortion for RGB and depth, the
stereo baseline, the depth scale, SDK and firmware.  The paper's calibration table (the
"Level-1 evidence" ``\\todo`` next to ``tab:hardware``) is generated from those records by
this tool -- from the completed **study** captures only, never from the pilot (prereg
section 10; the pilot root is refused) and never typed by hand.

Per camera (node), every capture record must report one and the same calibration
(serial, model, firmware, SDK, intrinsics, baseline, depth scale); a camera whose
calibration differs between captures stops the tool with the captures that differ.

* RealSense (node_a D435if, node_b D435i): the recorded intrinsics are the device's own,
  with its distortion model and coefficients, for the RGB, depth and IR streams.
* ZED 2i (node_c): the recorded ``intrinsics`` are those of the rectified images (all
  distortion coefficients 0, correct for the saved frames); the raw left/right
  calibration with distortion is ``calibration_raw`` (prereg 13.1) and is tabulated too.

Writes ``<output_dir>/calibration.csv`` (one row per camera and stream, every
coefficient) and ``<output_dir>/calibration_tabular.tex`` (the tabular only; the paper
keeps the float around its ``\\input``).

    python scripts/camera_calibration_table.py --data_dir data/raw/camera \\
        --output_dir analysis/camera
"""

import argparse
import glob
import json
import os
import sys
from typing import Any, Dict, List, Optional, Sequence

import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "scripts"))

from camera_labels import refuse_pilot  # noqa: E402

NODES = ("node_a", "node_b", "node_c")
TEX_SENSOR = {"node_a": "D435if", "node_b": "D435i", "node_c": "ZED 2i"}
#: (record path, stream label) of the tabulated intrinsics, in table order
STREAMS = ((("intrinsics", "rgb"), "RGB"), (("intrinsics", "depth"), "depth"),
           (("intrinsics", "ir"), "IR"), (("calibration_raw", "left"), "raw left"),
           (("calibration_raw", "right"), "raw right"))
#: the fields that must be identical in every record of one camera
CAMERA_FIELDS = ("camera_model", "serial", "firmware", "sdk_version", "stereo_baseline_mm",
                 "depth_scale_mm", "intrinsics", "calibration_raw")
GENERATED = "% generated by scripts/camera_calibration_table.py -- do not edit by hand"


def _get(record: Dict[str, Any], path: Sequence[str]) -> Any:
    for key in path:
        if not isinstance(record, dict):
            return None
        record = record.get(key)
    return record


def load_records(data_dir: str) -> Dict[str, List[Dict[str, Any]]]:
    """{node: [capture record, ...]} of the study root, in capture-id order."""
    refuse_pilot(data_dir)
    out: Dict[str, List[Dict[str, Any]]] = {}
    for node in NODES:
        paths = sorted(glob.glob(os.path.join(data_dir, node, "_captures", "*.json")))
        recs = []
        for p in paths:
            with open(p, encoding="utf-8") as fh:
                rec = json.load(fh)
            rec["_record"] = os.path.relpath(p, data_dir)
            recs.append(rec)
        if recs:
            out[node] = recs
    if not out:
        raise SystemExit("no capture records under %s/<node>/_captures/" % data_dir)
    return out


def one_calibration(node: str, records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """The camera's calibration, identical in every record; ValueError naming the
    captures that differ from the first one otherwise."""
    ref = {f: records[0].get(f) for f in CAMERA_FIELDS}
    differ = [r.get("capture_id", r["_record"]) for r in records[1:]
              if any(r.get(f) != ref[f] for f in CAMERA_FIELDS)]
    if differ:
        fields = sorted({f for r in records[1:] for f in CAMERA_FIELDS if r.get(f) != ref[f]})
        raise ValueError("%s: the calibration (%s) differs from %s in %d capture(s): %s"
                         % (node, ", ".join(fields), records[0].get("capture_id"), len(differ),
                            ", ".join(map(str, differ[:10]))))
    missing = [f for f in ("serial", "firmware", "sdk_version", "stereo_baseline_mm")
               if ref.get(f) is None]
    if missing or not _get(ref, ("intrinsics", "rgb")) or not _get(ref, ("intrinsics", "depth")):
        raise ValueError("%s: calibration incomplete (%s)" % (node, ", ".join(missing) or
                                                              "rgb/depth intrinsics"))
    return ref


def calibration_rows(records: Dict[str, List[Dict[str, Any]]]) -> pd.DataFrame:
    rows = []
    for node in NODES:
        if node not in records:
            continue
        cal = one_calibration(node, records[node])
        for path, label in STREAMS:
            intr = _get(cal, path)
            if not intr:
                continue
            row = {"node": node, "sensor": TEX_SENSOR[node], "camera_model": cal["camera_model"],
                   "serial": str(cal["serial"]), "firmware": str(cal["firmware"]),
                   "sdk_version": str(cal["sdk_version"]), "stream": label,
                   "width": int(intr["width"]), "height": int(intr["height"]),
                   "fx": float(intr["fx"]), "fy": float(intr["fy"]),
                   "ppx": float(intr["ppx"]), "ppy": float(intr["ppy"]),
                   "distortion_model": str(intr.get("model")),
                   "coeffs": " ".join(repr(float(c)) for c in intr.get("coeffs") or []),
                   "stereo_baseline_mm": float(cal["stereo_baseline_mm"]),
                   "depth_scale_mm": cal.get("depth_scale_mm"),
                   "n_captures": len(records[node])}
            rows.append(row)
    return pd.DataFrame(rows)


def _coeffs_tex(coeffs: str) -> str:
    """The first five distortion coefficients (k1 k2 p1 p2 k3), four decimals."""
    vals = [float(c) for c in str(coeffs).split()][:5] if isinstance(coeffs, str) and coeffs else []
    return ", ".join("%.4f" % v for v in vals) if vals else "--"


def tabular(rows: pd.DataFrame) -> str:
    out = [GENERATED, r"\begin{tabular}{@{}llccccccc@{}}", r"\toprule",
           r"\textbf{Camera} & \textbf{Stream} & \textbf{Resolution} & $f_x$ & $f_y$ & $c_x$ & "
           r"$c_y$ & \textbf{Distortion $k_1, k_2, p_1, p_2, k_3$} & \textbf{Baseline (mm)} \\",
           r"\midrule"]
    for k, (node, g) in enumerate(rows.groupby("node", sort=False)):
        if k:
            out.append(r"\midrule")
        first = g.iloc[0]
        head = r"\shortstack[l]{%s\\{\footnotesize S/N %s, FW %s}}" % (
            first["sensor"], first["serial"], first["firmware"].replace("_", r"\_"))
        for i, (_, r) in enumerate(g.iterrows()):
            out.append(" & ".join([
                (r"\multirow{%d}{*}{%s}" % (len(g), head)) if i == 0 else "", r["stream"],
                r"%d $\times$ %d" % (r["width"], r["height"]), "%.2f" % r["fx"], "%.2f" % r["fy"],
                "%.2f" % r["ppx"], "%.2f" % r["ppy"], _coeffs_tex(r["coeffs"]),
                ("%.2f" % r["stereo_baseline_mm"]) if i == 0 else ""]) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data_dir", default=os.path.join("data", "raw", "camera"))
    ap.add_argument("--output_dir", default=os.path.join("analysis", "camera"))
    args = ap.parse_args(argv)
    refuse_pilot(args.data_dir, args.output_dir)
    rows = calibration_rows(load_records(args.data_dir))
    os.makedirs(args.output_dir, exist_ok=True)
    rows.to_csv(os.path.join(args.output_dir, "calibration.csv"), index=False, lineterminator="\n")
    with open(os.path.join(args.output_dir, "calibration_tabular.tex"), "w", encoding="utf-8",
              newline="\n") as fh:
        fh.write(tabular(rows))
    for _, r in rows.iterrows():
        print("%s %-9s %4dx%-4d fx %.2f fy %.2f cx %.2f cy %.2f  %s  (%d captures)"
              % (r["sensor"], r["stream"], r["width"], r["height"], r["fx"], r["fy"], r["ppx"],
                 r["ppy"], r["distortion_model"], r["n_captures"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
