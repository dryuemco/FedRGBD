"""The reference numbers in paper/main.tex must match analysis/summary_table.csv.

CLAUDE.md rule 4 says no number is typed into the paper by hand.

* ``tab:fullmetrics``, ``tab:dirichlet`` and ``tab:lowdata`` \\input a tabular
  generated by ``scripts/export_latex_tables.py`` (reference rows from the analysis,
  federated rows ``\\PHs`` placeholders).  This test checks that main.tex inputs
  them inside the right table, and re-derives every reference cell of the
  generated files -- balanced accuracy pooled (primary) and client mean
  (secondary), mean and 95 % CI -- from ``analysis/summary_table.csv``.
* ``tab:protocol_effect`` still carries its group-level accuracy cells inline and
  is pinned here cell by cell.
* The superseded final-epoch reference cells of tab:dirichlet / tab:lowdata and
  the old communication volume must not reappear.
"""

import os
import re

import pandas as pd
import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN_TEX = os.path.join(ROOT, "paper", "main.tex")
SUMMARY = os.path.join(ROOT, "analysis", "summary_table.csv")

pytestmark = pytest.mark.skipif(
    not (os.path.isfile(MAIN_TEX) and os.path.isfile(SUMMARY)),
    reason="paper/main.tex and analysis/summary_table.csv are both needed")

# the mean +- std columns of the generated tab:fullmetrics after its two balanced-
# accuracy columns (pooled primary and client mean, both mean [CI]), in order; the
# first entry stands for those two and is checked separately.  Percentages except MCC.
FULLMETRICS_COLUMNS = [
    ("selected_test_balanced_accuracy", 100.0),
    ("selected_test_mcc", 1.0),
    ("selected_test_accuracy", 100.0),
    ("selected_test_recall", 100.0),
    ("selected_test_specificity", 100.0),
    ("selected_test_macro_f1", 100.0),
    ("selected_test_roc_auc", 100.0),
]


def _summary():
    df = pd.read_csv(SUMMARY)
    return df[df.protocol == "group"]


def _cells(line):
    """The ``$a \\pm b$`` pairs of one LaTeX table row, in order."""
    return [(float(a), float(b)) for a, b in
            re.findall(r"\$([0-9.]+) \\pm ([0-9.]+)\$", line)]


def _row(tex, table_label, method, distribution_block):
    """Find one ``& <method> &`` row inside the named table environment."""
    start = tex.index(r"\label{%s}" % table_label)
    end = tex.index(r"\end{table", start)
    block = tex[start:end]
    # the non-IID rows come after the \midrule that follows the IID ones
    halves = block.split(r"\multirow")
    half = halves[1] if distribution_block == "iid" else halves[2]
    for line in half.splitlines():
        # the method cell may carry a scarce-minority marker, e.g. "Local-only$^{\dagger}$"
        if re.search(r"&\s*%s\s*(\$\^\{\\dagger\}\$)?\s*&" % re.escape(method), line):
            return line
    raise AssertionError("no %r row in %s (%s)" % (method, table_label, distribution_block))


def _lookup(summary, distribution, kind, metric):
    sel = summary[(summary.distribution == distribution) & (summary.kind == kind)
                  & (summary.metric == metric)]
    assert len(sel) == 1, "expected one %s/%s/%s row, got %d" % (
        distribution, kind, metric, len(sel))
    return float(sel.iloc[0]["mean"]), float(sel.iloc[0]["std"])


TABLES = os.path.join(ROOT, "paper", "tables")
GENERATED = {"tab:fullmetrics": "fullmetrics_tabular.tex",
             "tab:dirichlet": "dirichlet_tabular.tex",
             "tab:lowdata": "lowdata_tabular.tex"}
PRIMARY_BA = "selected_test_balanced_accuracy"
SECONDARY_BA = "selected_test_clientmean_balanced_accuracy"


def _generated(name):
    return open(os.path.join(TABLES, name), encoding="utf-8").read()


def _ci_cells(line):
    """``m [lo, hi]`` cells of one generated row, in order."""
    return [tuple(float(x) for x in t) for t in
            re.findall(r"([0-9.]+) \[([0-9.]+), ([0-9.]+)\]", line)]


def _full(summary, distribution, kind, metric):
    sel = summary[(summary.distribution == distribution) & (summary.kind == kind)
                  & (summary.metric == metric)]
    assert len(sel) == 1, "expected one %s/%s/%s row, got %d" % (
        distribution, kind, metric, len(sel))
    row = sel.iloc[0]
    # a cell printed under the declared aggregation must have been computed under it,
    # from prediction files, with the cluster bootstrap
    assert row["aggregation"] == "pooled", (distribution, kind, metric, row["aggregation"])
    assert str(row["ci_method"]).startswith("cluster_bootstrap"), (distribution, kind, metric)
    return row


def _scarce():
    flags = pd.read_csv(os.path.join(ROOT, "analysis", "leakage", "scarce_minority.csv"))
    return {(r.partition, r.kind) for r in flags[flags.flagged == 1].itertuples()}


def _expected_dagger(scarce, distribution, metric):
    """Pooled cells: the pooled unit's flag (centralized); client-mean cells: per client."""
    if metric == SECONDARY_BA:
        return (distribution, "fl") in scarce or (distribution, "local") in scarce
    return (distribution, "centralized") in scarce


def _cells_with_dagger(line):
    return [(tuple(float(x) for x in m[:3]), bool(m[3])) for m in
            re.findall(r"([0-9.]+) \[([0-9.]+), ([0-9.]+)\](\$\^\{\\dagger\}\$)?", line)]


def _check_ci(cell, row, what):
    for printed, value in zip(cell, (row["mean"], row["ci_low"], row["ci_high"])):
        assert printed == pytest.approx(round(float(value) * 100, 1), abs=0.051), (
            "%s: paper %s, analysis %.4f" % (what, cell, float(value) * 100))


@pytest.mark.parametrize("label,name", sorted(GENERATED.items()))
def test_paper_inputs_the_generated_tabular(label, name):
    tex = open(MAIN_TEX, encoding="utf-8").read()
    start = tex.index(r"\label{%s}" % label)
    end = tex.index(r"\end{table", start)
    block = tex[start:end]
    assert r"\input{tables/%s}" % name in block, "%s does not input %s" % (label, name)
    assert r"\begin{tabular}" not in block, "%s still holds a hand-typed tabular" % label
    assert os.path.isfile(os.path.join(TABLES, name))


REFERENCE_ROWS = [("centralized", "Centralized"), ("local", "Local-only")]


@pytest.mark.parametrize("distribution,block", [("iid", 1), ("non_iid_label", 2)])
@pytest.mark.parametrize("kind,method", REFERENCE_ROWS)
def test_fullmetrics_rows_match_summary(distribution, block, kind, method):
    summary = _summary()
    halves = _generated("fullmetrics_tabular.tex").split(r"\multirow")
    line = [l for l in halves[block].splitlines() if "& %s &" % method in l][0]
    cis = _ci_cells(line)
    assert len(cis) == 2, line
    _check_ci(cis[0], _full(summary, distribution, kind, PRIMARY_BA),
              "%s %s BA pooled" % (distribution, method))
    _check_ci(cis[1], _full(summary, distribution, kind, SECONDARY_BA),
              "%s %s BA client mean" % (distribution, method))
    scarce = _scarce()
    for (cell, dagger), metric in zip(_cells_with_dagger(line), (PRIMARY_BA, SECONDARY_BA)):
        assert dagger == _expected_dagger(scarce, distribution, metric), (distribution, method, metric)
    cells = _cells(line)
    assert len(cells) == len(FULLMETRICS_COLUMNS) - 1
    for (printed_mean, printed_std), (metric, scale) in zip(cells, FULLMETRICS_COLUMNS[1:]):
        mean, std = _lookup(summary, distribution, kind, metric)
        digits = 2 if scale == 1.0 else 1
        assert printed_mean == pytest.approx(round(mean * scale, digits), abs=0.05), (
            "%s %s %s: paper says %.2f, analysis says %.4f"
            % (distribution, method, metric, printed_mean, mean * scale))
        assert printed_std == pytest.approx(round(std * scale, digits), abs=0.05), (
            "%s %s %s std: paper says %.2f, analysis says %.4f"
            % (distribution, method, metric, printed_std, std * scale))


def test_fullmetrics_labels_are_where_the_cells_assume():
    text = _generated("fullmetrics_tabular.tex")
    header = [l for l in text.splitlines() if l.startswith(r"\textbf{Dist.}")][0]
    order = [r"\textbf{Bal.\ acc.}", r"\textbf{Bal.\ acc.,} \textbf{client mean}", r"\textbf{MCC}",
             r"\textbf{Acc.}", r"\textbf{Sens.}", r"\textbf{Spec.}", r"\textbf{Macro-}$F_1$",
             r"\textbf{ROC-AUC}"]
    positions = [header.index(h) for h in order]
    assert positions == sorted(positions), header
    blocks = text.split(r"\multirow")
    assert blocks[1].startswith("{5}{*}{IID}") and blocks[2].startswith("{5}{*}{Non-IID}")


def _two_block_rows(text, method):
    """The pooled-block and client-mean-block rows of one method, in order."""
    return [l for l in text.splitlines() if re.search(r"(^|& )%s &" % re.escape(method), l)]


@pytest.mark.parametrize("kind,method", REFERENCE_ROWS)
def test_dirichlet_reference_rows_match_summary(kind, method):
    summary = _summary()
    text = _generated("dirichlet_tabular.tex")
    header = [l for l in text.splitlines() if l.startswith(r"\textbf{Method}")][0]
    alphas = re.findall(r"alpha\{=\}([0-9.]+)", header)
    parts = {"0.1": "dirichlet_0.1", "0.5": "dirichlet_0.5", "1.0": "dirichlet_1"}
    cols = [parts[a] for a in alphas]
    assert sorted(cols) == sorted(parts.values())
    pooled, mean = _two_block_rows(text, method)
    scarce = _scarce()
    for line, metric in ((pooled, PRIMARY_BA), (mean, SECONDARY_BA)):
        cells = _cells_with_dagger(line)
        assert len(cells) == len(cols), line
        for (cell, dagger), dist in zip(cells, cols):
            _check_ci(cell, _full(summary, dist, kind, metric), "%s %s %s" % (dist, method, metric))
            assert dagger == _expected_dagger(scarce, dist, metric), (dist, method, metric)
    lines = text.splitlines()
    assert lines.index([l for l in lines if "(primary)" in l][0]) < lines.index(pooled)
    assert lines.index(pooled) < lines.index([l for l in lines if "(secondary)" in l][0]) \
        < lines.index(mean)


def test_dirichlet_columns_follow_the_measured_skew():
    skew = pd.read_csv(os.path.join(ROOT, "analysis", "partition_skew.csv"))
    skew = skew[skew.node == "ALL"].set_index("partition")["jsd"]
    header = [l for l in _generated("dirichlet_tabular.tex").splitlines()
              if l.startswith(r"\textbf{Method}")][0]
    order = ["dirichlet_%s" % ("1" if a == "1.0" else a)
             for a in re.findall(r"alpha\{=\}([0-9.]+)", header)]
    assert list(skew[order]) == sorted(skew[order])
    jsd_row = [l for l in _generated("dirichlet_tabular.tex").splitlines() if "measured skew (JSD)" in l][0]
    printed = [float(x) for x in re.findall(r"\{\\footnotesize ([0-9.]+)\}", jsd_row)]
    assert printed == [round(float(skew[p]), 3) for p in order]


@pytest.mark.parametrize("kind,method", REFERENCE_ROWS)
def test_lowdata_reference_rows_match_summary(kind, method):
    summary = _summary()
    rows = _two_block_rows(_generated("lowdata_tabular.tex"), method)
    assert len(rows) == 4             # pooled IID, pooled Non-IID, mean IID, mean Non-IID
    scarce = _scarce()
    for line, (dist, metric) in zip(rows, [("iid", PRIMARY_BA), ("non_iid_label", PRIMARY_BA),
                                           ("iid", SECONDARY_BA), ("non_iid_label", SECONDARY_BA)]):
        cols = [dist, dist + "_sub0.05", dist + "_sub0.01"]
        cells = _cells_with_dagger(line)
        assert len(cells) == 3, line
        for (cell, dagger), col in zip(cells, cols):
            _check_ci(cell, _full(summary, col, kind, metric), "%s %s %s" % (col, method, metric))
            assert dagger == _expected_dagger(scarce, col, metric), (col, method, metric)


def test_lowdata_labels_are_where_the_cells_assume():
    text = _generated("lowdata_tabular.tex")
    lines = text.splitlines()
    header = [l for l in lines if l.startswith(r"\textbf{Dist.}")][0]
    rhos = re.findall(r"rho\{=\}([0-9.]+)", header)
    assert rhos == ["1.00", "0.05", "0.01"]
    primary = [i for i, l in enumerate(lines) if "(primary)" in l]
    secondary = [i for i, l in enumerate(lines) if "(secondary)" in l]
    assert len(primary) == len(secondary) == 1 and primary[0] < secondary[0]
    labels = [re.search(r"\{\*\}\{([^}]+)\}", l).group(1) for l in lines if r"\multirow" in l]
    assert labels == ["IID", "Non-IID", "IID", "Non-IID"]


