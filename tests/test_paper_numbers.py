def test_communication_volume_is_the_measured_one():
    """Three payloads per client per round: 165.5 MB for three rounds, not 110.3."""
    tex = open(MAIN_TEX, encoding="utf-8").read()
    runs = pd.read_csv(os.path.join(ROOT, "analysis", "runs.csv"))
    fl = runs[(runs.protocol == "group") & (runs.kind == "fl") & (runs.num_rounds == 3)]
    mb = sorted(set(round(float(v), 1) for v in fl.final_cumulative_mb.dropna()))
    assert mb == [165.5]
    assert "110.3" not in tex
    assert "$165.5$\\,MB" in tex
    assert r"B(R) \;=\; 3\,R\,K\,|w|" in tex


@pytest.mark.parametrize("distribution,kind,method", [
    ("iid", "centralized", "Centralized"),
    ("iid", "local", "Local-only"),
    ("non_iid_label", "centralized", "Centralized"),
    ("non_iid_label", "local", "Local-only"),
])
def test_protocol_effect_group_column_matches_summary(distribution, kind, method):
    """The group-level column of tab:protocol_effect is selected-round accuracy."""
    tex = open(MAIN_TEX, encoding="utf-8").read()
    summary = _summary()
    line = _row(tex, "tab:protocol_effect", method, distribution)
    cells = _cells(line)
    assert len(cells) == 2, "expected an image-level and a group-level cell"

    mean, std = _lookup(summary, distribution, kind, "selected_test_accuracy")
    printed_mean, printed_std = cells[1]
    assert printed_mean == pytest.approx(round(mean * 100, 1), abs=0.05), (
        "%s %s: paper says %.2f, analysis says %.4f"
        % (distribution, method, printed_mean, mean * 100))
    assert printed_std == pytest.approx(round(std * 100, 1), abs=0.05)


def test_paper_does_not_report_the_superseded_final_epoch_references():
    """78.3 % / 90.9 % may appear only where they are named as the old protocol.

    They were the headline references before the selection rule was declared.
    Any *unlabelled* occurrence is a cell that was missed when the tables were
    regenerated.
    """
    tex = open(MAIN_TEX, encoding="utf-8").read()
    for value in ("78.3", "90.9"):
        # a whole value, so that unrelated v1 numbers such as 78.36 do not match
        for match in re.finditer(re.escape(value) + r"(?!\d)", tex):
            window = tex[max(0, match.start() - 400):match.start() + 200]
            assert "final-epoch" in window or "final epoch" in window, (
                "%r appears at offset %d without being labelled as the superseded "
                "final-epoch protocol" % (value, match.start()))


def test_time_table_reports_both_aggregations_from_the_summary():
    """tab:time (\input by main.tex) prints balanced accuracy pooled and as the client
    mean, with the cluster-bootstrap interval, for the 3-round default-point runs."""
    text = open(os.path.join(TABLES, "time.tex"), encoding="utf-8").read()
    assert text.count(r"\begin{table*}") == 1
    summary = _summary()
    names = {"FedAvg": ("fedavg", None), r"FedProx($\mu$=0.01)": ("fedprox_0.01", 0.01)}
    checked = 0
    for line in text.splitlines():
        m = re.match(r"3N (IID|Label skew) (.+?) & ", line)
        if not m or m.group(2) not in names:
            continue
        dist = "iid" if m.group(1) == "IID" else "non_iid_label"
        strategy = names[m.group(2)][0]
        cis = _ci_cells(line)[1:]            # the first is the time interval
        assert len(cis) == 2, line
        for cell, metric in zip(cis, (PRIMARY_BA, SECONDARY_BA)):
            sel = summary[(summary.distribution == dist) & (summary.kind == "fl")
                          & (summary.strategy == strategy) & (summary.metric == metric)
                          & (summary.num_rounds == 3) & (summary.local_epochs == 5)
                          & (summary.lr == 0.001) & (summary.power_config == "heterogeneous")]
            assert len(sel) == 1
            _check_ci(cell, sel.iloc[0], "time %s %s %s" % (dist, strategy, metric))
            checked += 1
    assert checked == 8


def test_aggregation_flip_list_header_matches_its_csv():
    csv = os.path.join(ROOT, "analysis", "aggregation_flips.csv")
    md = open(os.path.join(ROOT, "analysis", "aggregation_flips.md"), encoding="utf-8").read()
    df = pd.read_csv(csv)
    for subset in ("full", "clean"):
        sub = df[df.subset == subset]
        line = [l for l in md.splitlines() if l.startswith("- %s set:" % subset)][0]
        numbers = [int(x) for x in re.findall(r"(\d+)", line)]
        assert numbers[:4] == [len(sub), int(sub.verdict_flip.sum()),
                               int((sub.direction_flip & ~sub.verdict_flip).sum()),
                               int((~sub.stable).sum())], line
    # every pair appears once: reference-vs-reference pairs are not duplicated per power group
    keys = df[["subset", "distribution", "a", "b"]].astype(str).agg("|".join, axis=1)
    assert keys.is_unique


def test_fedbn_bn_share_is_the_computed_one():
    """FedBN transmits the full model; the BN share of a transfer comes from
    scripts/fedbn_payload.py (analysis/fedbn_payload.json), not from the keyboard."""
    import json

    tex = open(MAIN_TEX, encoding="utf-8").read()
    path = os.path.join(ROOT, "analysis", "fedbn_payload.json")
    share = json.load(open(path, encoding="utf-8"))["bn_share_of_bytes"]
    assert "never transmitted" not in tex
    assert "$%.2f$\%% of one model transfer" % (100 * share) in tex
    try:
        import torch  # noqa: F401
    except ImportError:
        return
    import sys
    sys.path.insert(0, ROOT)
    from scripts.fedbn_payload import bn_payload_share
    assert bn_payload_share()["bn_share_of_bytes"] == pytest.approx(share, rel=0, abs=1e-12)
